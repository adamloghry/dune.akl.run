const fold = (s: string) =>
  s.normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[‘’]/g, "'").replace(/[“”]/g, '"').toUpperCase();

export const textWidth = (s: string, scale = 1) => fold(s).length * 6 * scale - scale;

/** Draw text; returns the x after the last glyph. */
export function drawText(p: Pix, s: string, x: number, y: number, c: Col, scale = 1, shadow?: Col) {
  for (const ch of fold(s)) {
    const g = G[ch] ?? G['?'];
    g.split('|').forEach((row, j) => [...row].forEach((v, i) => {
      if (v !== '#') return;
      if (shadow) p.rect(x + i * scale + scale, y + j * scale + scale, scale, scale, shadow);
    }));
    g.split('|').forEach((row, j) => [...row].forEach((v, i) => { if (v === '#') p.rect(x + i * scale, y + j * scale, scale, scale, c); }));
    x += 6 * scale;
  }
  return x;
}

/** Greedy word wrap to a max width in pixels. */
export function wrap(s: string, max: number, scale = 1) {
  const words = s.split(/\s+/);
  const lines: string[] = [];
  let cur = '';
  for (const w of words) {
    const t = cur ? `${cur} ${w}` : w;
    if (textWidth(t, scale) <= max || !cur) cur = t; else { lines.push(cur); cur = w; }
  }
  if (cur) lines.push(cur);
  return lines;
}
